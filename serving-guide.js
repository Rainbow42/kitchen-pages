function servingGuide(name){
 const g=SERVING_GUIDES[name];if(!g)return '';
 const rows=g.extras.map(([food,grams])=>`<tr><td>${esc(NUTRITION.foods[food].name)}</td><td>${number(grams)} г</td><td>${number(grams*2)} г</td></tr>`).join('');
 return `<section class="serving-guide"><h3>Перед едой</h3><p>${esc(g.base)}</p>${rows?`<div class="table-scroll"><table class="portions"><thead><tr><th>Достать / отмерить</th><th>Одному</th><th>Двоим</th></tr></thead><tbody>${rows}</tbody></table></div>`:'<p><strong>Ничего дополнительно добавлять не нужно.</strong></p>'}${g.note?`<p>${esc(g.note)}</p>`:''}<small>Изображение помогает узнать компоненты. Размер порции определяйте по граммам, а не на глаз; упаковки показаны для узнавания.</small></section>`;
}

